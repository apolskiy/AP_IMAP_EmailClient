"""Failure keywords raised by the reader (catalog: ``docs/keywords.md``)."""

from enum import StrEnum


class ReaderKeyword(StrEnum):
    """Keywords for failures of the reader tool itself (``READER_`` prefix)."""

    IMAP_CONNECTION_REFUSED = "READER_IMAP_CONNECTION_REFUSED"
    IMAP_DNS_FAILURE = "READER_IMAP_DNS_FAILURE"
    IMAP_CONNECTION_TIMEOUT = "READER_IMAP_CONNECTION_TIMEOUT"
    IMAP_READ_TIMEOUT = "READER_IMAP_READ_TIMEOUT"
    IMAP_CONNECTION_DROPPED = "READER_IMAP_CONNECTION_DROPPED"
    IMAP_SOCKET_WRITE_FAILED = "READER_IMAP_SOCKET_WRITE_FAILED"
    IMAP_TLS_HANDSHAKE_FAILED = "READER_IMAP_TLS_HANDSHAKE_FAILED"
    IMAP_AUTH_FAILED = "READER_IMAP_AUTH_FAILED"
    IMAP_PROTOCOL_ERROR = "READER_IMAP_PROTOCOL_ERROR"
    IMAP_CONNECTION_LIMIT = "READER_IMAP_CONNECTION_LIMIT"
    IMAP_UIDVALIDITY_CHANGED = "READER_IMAP_UIDVALIDITY_CHANGED"
    MAILBOX_NONE_ACCESSIBLE = "READER_MAILBOX_NONE_ACCESSIBLE"
    MAILBOX_EXPECTED_FOLDER_INACCESSIBLE = "READER_MAILBOX_EXPECTED_FOLDER_INACCESSIBLE"
    MAILBOX_FILTERED_TO_INACCESSIBLE = "READER_MAILBOX_FILTERED_TO_INACCESSIBLE"
    MIME_DECODE_FAILED = "READER_MIME_DECODE_FAILED"
    PARSE_NO_HTML_PART = "READER_PARSE_NO_HTML_PART"


class ReaderCaseKeyword(StrEnum):
    """Test-case outcomes the reader detects (``CASE_`` prefix): the tool worked, the email is wrong."""

    EMAIL_NOT_RECEIVED = "CASE_EMAIL_NOT_RECEIVED"
    EMAIL_COUNT_EXCEEDED = "CASE_EMAIL_COUNT_EXCEEDED"
    DUPLICATE_DELIVERY = "CASE_DUPLICATE_DELIVERY"
    LINK_NOT_FOUND = "CASE_LINK_NOT_FOUND"
    LINK_AMBIGUOUS = "CASE_LINK_AMBIGUOUS"
    LINK_HTML_TEXT_MISMATCH = "CASE_LINK_HTML_TEXT_MISMATCH"
    LINK_RECIPIENT_MISMATCH = "CASE_LINK_RECIPIENT_MISMATCH"
