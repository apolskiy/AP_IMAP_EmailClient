"""Failure keywords raised by the sender (catalog: ``docs/keywords.md``)."""

from enum import StrEnum


class SenderKeyword(StrEnum):
    """Keywords for failures of the sender tool itself (``SENDER_`` prefix)."""

    SMTP_SERVER_UNREACHABLE = "SENDER_SMTP_SERVER_UNREACHABLE"
    SMTP_CONNECTION_REFUSED = "SENDER_SMTP_CONNECTION_REFUSED"
    SMTP_CONNECTION_TIMEOUT = "SENDER_SMTP_CONNECTION_TIMEOUT"
    SMTP_READ_TIMEOUT = "SENDER_SMTP_READ_TIMEOUT"
    SMTP_CONNECTION_DROPPED = "SENDER_SMTP_CONNECTION_DROPPED"
    SMTP_SOCKET_WRITE_FAILED = "SENDER_SMTP_SOCKET_WRITE_FAILED"
    SMTP_TLS_HANDSHAKE_FAILED = "SENDER_SMTP_TLS_HANDSHAKE_FAILED"
    SMTP_AUTH_FAILED = "SENDER_SMTP_AUTH_FAILED"
    SMTP_RECIPIENT_REJECTED = "SENDER_SMTP_RECIPIENT_REJECTED"
    SMTP_MESSAGE_REJECTED = "SENDER_SMTP_MESSAGE_REJECTED"
    IMAP_APPEND_FAILED = "SENDER_IMAP_APPEND_FAILED"
    PARTIAL_FAILURE = "SENDER_PARTIAL_FAILURE"
    SEND_TIMEOUT = "SENDER_SEND_TIMEOUT"
    BATCH_TIMEOUT = "SENDER_BATCH_TIMEOUT"
    NEGATIVE_COUNT = "SENDER_NEGATIVE_COUNT"


class SenderCaseKeyword(StrEnum):
    """Condition errors in what the caller asked for (``CASE_`` prefix)."""

    CONDITION_INVALID_INPUT = "CASE_CONDITION_INVALID_INPUT"
    CONDITION_NEGATIVE_COUNT = "CASE_CONDITION_NEGATIVE_COUNT"
